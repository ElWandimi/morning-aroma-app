// Runs as part of `npm run build` (see package.json). server.js is a plain CommonJS Node script
// (no build step of its own, no transpilation) and needs a handful of specific exports from
// src/data/index.js at runtime -- but that file is an ES module bundled by Vite for the browser,
// not something a plain `require()` can read directly. Rather than duplicate this data by hand in
// server.js (which would silently drift from the real source the moment either one changed),
// this script imports the real, current values directly from the real source file and writes out
// a small, generated CommonJS module with just what the server actually needs.
import { PAGE_META, SLUG_TO_PAGE, KNOWN_ROUTES, PRODUCTS } from "../src/data/index.js";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(__dirname, "../dist-data");
fs.mkdirSync(outDir, { recursive: true });

const minimalProducts = PRODUCTS.map((p) => ({ id: p.id, name: p.name, country: p.country, note: p.note }));

const output = `// Generated by scripts/generate-route-meta.mjs at build time -- do not hand-edit.
// Regenerate by running the build; this file is not committed (see .gitignore).
module.exports = {
  PAGE_META: ${JSON.stringify(PAGE_META, null, 2)},
  SLUG_TO_PAGE: ${JSON.stringify(SLUG_TO_PAGE, null, 2)},
  KNOWN_ROUTES: new Set(${JSON.stringify([...KNOWN_ROUTES])}),
  PRODUCTS: ${JSON.stringify(minimalProducts, null, 2)},
};
`;

fs.writeFileSync(path.join(outDir, "routeMeta.cjs"), output);
console.log(`Generated dist-data/routeMeta.cjs (${minimalProducts.length} products, ${Object.keys(PAGE_META).length} static pages)`);
