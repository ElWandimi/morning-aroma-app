// Runs as part of `npm run build` (see package.json). server.js is a plain CommonJS Node script
// (no build step of its own, no transpilation) and needs a handful of specific exports from
// src/data/index.js at runtime -- but that file is an ES module bundled by Vite for the browser,
// not something a plain `require()` can read directly. Rather than duplicate this data by hand in
// server.js (which would silently drift from the real source the moment either one changed),
// this script imports the real, current values directly from the real source file and writes out
// a small, generated CommonJS module with just what the server actually needs.
import { PAGE_META, SLUG_TO_PAGE, KNOWN_ROUTES, PRODUCTS, MOMENTS, BREW_GUIDES, COUNTRIES, GROWING_FACTORS } from "../src/data/index.js";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(__dirname, "../dist-data");
fs.mkdirSync(outDir, { recursive: true });

const minimalProducts = PRODUCTS.map((p) => ({ id: p.id, name: p.name, country: p.country, note: p.note }));
// Minimal fields only, same reasoning as minimalProducts above -- just what server.cjs's
// resolveMeta actually needs to mirror App.jsx's own getPageMeta for these route types, not a
// full copy of each data set. COURSES intentionally not included here -- see the file-level
// comment for why.
const minimalMoments = MOMENTS.map((m) => ({ id: m.id, name: m.name, benefit: m.benefit }));
const minimalBrewGuides = BREW_GUIDES.map((b) => ({ name: b.name, flavor: b.flavor }));
const minimalCountries = COUNTRIES.map((c) => ({ name: c.name, climate: c.climate }));
const minimalGrowingFactors = GROWING_FACTORS.map((f) => ({ name: f.name, explain: f.explain }));

const output = `// Generated by scripts/generate-route-meta.mjs at build time -- do not hand-edit.
// Regenerate by running the build; this file is not committed (see .gitignore).
module.exports = {
  PAGE_META: ${JSON.stringify(PAGE_META, null, 2)},
  SLUG_TO_PAGE: ${JSON.stringify(SLUG_TO_PAGE, null, 2)},
  KNOWN_ROUTES: new Set(${JSON.stringify([...KNOWN_ROUTES])}),
  PRODUCTS: ${JSON.stringify(minimalProducts, null, 2)},
  MOMENTS: ${JSON.stringify(minimalMoments, null, 2)},
  BREW_GUIDES: ${JSON.stringify(minimalBrewGuides, null, 2)},
  COUNTRIES: ${JSON.stringify(minimalCountries, null, 2)},
  GROWING_FACTORS: ${JSON.stringify(minimalGrowingFactors, null, 2)},
};
`;

fs.writeFileSync(path.join(outDir, "routeMeta.cjs"), output);
console.log(`Generated dist-data/routeMeta.cjs (${minimalProducts.length} products, ${minimalMoments.length} moments, ${minimalBrewGuides.length} brew guides, ${minimalCountries.length} countries, ${minimalGrowingFactors.length} growing factors, ${Object.keys(PAGE_META).length} static pages)`);
